public class CubeData {

    Faces up;
    Faces front;
    Faces right;
    Faces back;
    Faces left;
    Faces down;

    public CubeData(Faces up, Faces front, Faces right, Faces back, Faces left, Faces down) {
        this.up = up;
        this.front = front;
        this.right = right;
        this.back = back;
        this.left = left;
        this.down = down;
    }
}
